import { loaderImage } from '../shared/loader-image.mjs';
import { readFile, writeFile, rename } from 'node:fs/promises';
import { resolve, dirname } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { build } from 'vite';
import { Script } from 'node:vm';
import react from '@vitejs/plugin-react';
import tailwindcss from '@tailwindcss/postcss';
import { getSiteOrigin } from '../shared/site-config.mjs';
import { serializeStructuredData } from '../shared/seo-data.mjs';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const site = JSON.parse(await readFile(resolve(root, 'lib/site.json'), 'utf8'));
const escapeHtml = value => value.replaceAll('&', '&amp;').replaceAll('<', '&lt;').replaceAll('"', '&quot;');
const logo = `data:image/png;base64,${(await readFile(resolve(root, 'public/arc-logo-transparent.png'))).toString('base64')}`;
const favicon = `data:image/png;base64,${(await readFile(resolve(root, 'public/favicon.png'))).toString('base64')}`;
const sharedConfig = {
  root,
  configFile: false,
  publicDir: false,
  define: { 'process.env.NODE_ENV': JSON.stringify('production') },
  resolve: { alias: { '@': root, 'next/image': resolve(root, 'scripts/standalone-image.tsx') } },
  plugins: [react(), {
    name: 'embed-standalone-images',
    resolveId(id) {
      if (id === 'virtual:arc-logo') return '\0virtual:arc-logo';
    },
    load(id) {
      if (id === '\0virtual:arc-logo') return `export default ${JSON.stringify(logo)};`;
    },
    transform(code, id) {
      if (id.split('?')[0].endsWith('.tsx') && !id.includes('node_modules')) {
        const usesLogo = code.includes('"/arc-logo-transparent.png"');
        // Pages deploys the homepage as index.html, not its local export filename.
        const content = code.replaceAll('"/arc-logo-transparent.png"', 'arcEmbeddedLogo').replaceAll('"/privacy"','"./privacy.html"').replaceAll('"/terms"','"./terms.html"').replaceAll('"/contact"','"./contact.html"').replaceAll('"/"','"./"').replaceAll('"/#faq"','"./#faq"').replaceAll('"/#home"','"./#home"');
        return (usesLogo ? 'import arcEmbeddedLogo from "virtual:arc-logo";\n' : '') + content;
      }
    },
  }],
  css: { postcss: { plugins: [tailwindcss()] } },
};
const result = await build({
  ...sharedConfig,
  build: {
    write: false,
    minify: true,
    cssCodeSplit: false,
    lib: { entry: resolve(root, 'scripts/standalone-entry.tsx'), name: 'ArcStandalone', formats: ['iife'] },
  },
});
await build({
  ...sharedConfig,
  build: {
    ssr: resolve(root, 'scripts/standalone-render.tsx'),
    outDir: resolve(root, '.seo-render'),
    emptyOutDir: true,
    rollupOptions: { output: { entryFileNames: 'render.mjs' } },
  },
});
const { pages } = await import(pathToFileURL(resolve(root, '.seo-render/render.mjs')).href);
const outputs = (Array.isArray(result) ? result : [result]).flatMap(bundle => bundle.output);
const js = outputs.filter(item => item.type === 'chunk').map(item => item.code).join('\n');
const css = outputs.filter(item => item.type === 'asset' && item.fileName.endsWith('.css')).map(item => item.source).join('\n');
if (!js || !css || !js.includes('data:image/png;base64,')) throw new Error('Standalone export is missing scripts, styles, or the embedded logo.');
new Script(js);
if (js.includes('process.env.NODE_ENV')) throw new Error('Standalone export contains an unresolved Node environment dependency.');
const origin = getSiteOrigin(site.url);
const renderHtml = (title,description,path) => {
const canonical = origin ? origin + path : '';
const indexable = Boolean(canonical) && (path === '/' || path === '/contact' || site.legalReviewed);
const page = path === '/' ? 'home' : path.slice(1);
const startup = `<div id="arc-startup"${page === 'home' ? ' class="arc-orbit-loader"' : ' hidden'} aria-hidden="true"><div class="arc-orbit-loader-mark"><span class="arc-orbit-loader-ring"></span><span class="brand-logo brand-logo--loader"><span class="brand-art"><img id="arc-startup-logo" src="${loaderImage}" alt="ARC" width="2020" height="778" loading="eager" fetchpriority="high" decoding="sync"></span><span class="brand-tagline">AUTOMATE · OPTIMIZE · ELEVATE</span></span></div><span class="arc-orbit-loader-name">Initializing production intelligence</span><span class="arc-orbit-loader-line"></span></div>`;
return `<!doctype html>
<!-- Generated from app/page.tsx by pnpm build. Do not edit this file directly. -->
<html lang="en" class="dark" data-arc-page="${page}"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><title>${escapeHtml(title)}</title><meta name="description" content="${escapeHtml(description)}"><link rel="icon" type="image/png" sizes="512x512" href="${favicon}"><meta name="robots" content="${indexable ? 'index,follow' : 'noindex,nofollow'}">${canonical ? `<link rel="canonical" href="${escapeHtml(canonical)}"><meta property="og:url" content="${escapeHtml(canonical)}"><meta property="og:image" content="${escapeHtml(origin)}/arc-logo.png"><meta property="og:image:alt" content="ARC — production automation"><meta name="twitter:image" content="${escapeHtml(origin)}/arc-logo.png">` : ''}<meta property="og:title" content="${escapeHtml(title)}"><meta property="og:description" content="${escapeHtml(description)}"><meta property="og:type" content="website"><meta name="twitter:card" content="summary"><meta name="twitter:title" content="${escapeHtml(title)}"><meta name="twitter:description" content="${escapeHtml(description)}"><style>${css.replaceAll('</style', '<\\/style')}</style></head>
<body>${startup}<div id="root">${pages[page]}</div>${origin ? `<script type="application/ld+json">${serializeStructuredData(site)}</script>` : ''}<noscript>Enable JavaScript to use the interactive sample verification.</noscript><script>${js.replaceAll('</script', '<\\/script')}</script></body></html>`;
};
for (const [file,title,description,path] of [['ARC (3).html',site.title,site.description,'/'],['contact.html','Contact ARC | Production Automation & Traceability','Contact ARC about production automation and component traceability. Email saas@arc-ai.in or call +91 6380436024.','/contact'],['privacy.html','Privacy Policy | ARC','How the ARC website handles your information.','/privacy'],['terms.html','Website Terms | ARC','Terms for using the ARC website.','/terms']]) {
const target=resolve(root,file);await writeFile(`${target}.tmp`,renderHtml(title,description,path));await rename(`${target}.tmp`,target);
}
console.log('Generated ARC (3).html from the React website with embedded scripts, styles and images.');
